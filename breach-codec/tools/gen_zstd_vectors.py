#!/usr/bin/env python3
"""Generate Zstd test frames with the REAL zstd library (python-zstandard) -> tests/zstd_vectors.luau"""
import base64, random, struct, json, sys, zstandard as z
random.seed(7)
def h32(b):
    h = 0
    for x in b: h = (h * 31 + x) & 0xFFFFFFFF
    return h
words = "the of and to in is that it was for on are as with his they at be this from have or by one had not but what all were when we there can an your which their said if do will each about how up out them then she many some so these would other into has more her two like him see time could no make than first been its who now people my made over did down only way find use may water long little very after words called just where most know".split()
def text(n):
    out, size = [], 0
    while size < n:
        w = random.choice(words) + random.choice([" ", " ", " ", ", ", ". ", "\n"]); out.append(w); size += len(w)
    return "".join(out).encode()[:n]
def structured(n):
    return b"".join(struct.pack("<IHfBB", i, i % 977, i * 0.25, i % 7, (i * 31) % 251) for i in range(n // 12 + 1))[:n]
def jsonish(n):
    rows = []
    while sum(map(len, rows)) < n:
        i = len(rows); rows.append(json.dumps({"id": i, "name": f"item{i % 300}", "pos": [i % 50, (i * 7) % 90, 3.5], "tags": ["a", "b", "c"][: i % 4], "active": i % 3 == 0}))
    return "\n".join(rows).encode()[:n]
rnd = lambda n: bytes(random.getrandbits(8) for _ in range(n))
base = {
 "empty": b"", "one byte": b"x", "short text": b"hello hello hello hello world",
 "rle": b"\x00" * 200000, "rle+tail": b"A" * 70000 + b"tail",
 "random 20k": rnd(20000), "text 120k": text(120000), "structured 100k": structured(100000),
 "json-ish 150k": jsonish(150000), "text 5k": text(5000), "mixed": text(40000) + rnd(3000) + structured(30000) + b"Z" * 5000,
}
cases = []
def add(name, data, comp, **kw):
    f = comp.compress(data) if not kw.get("stream") else kw["stream"](comp, data)
    cases.append({"name": name, "b64": base64.b64encode(f).decode(), "len": len(data), "hash": h32(data)})
for name, data in base.items():
    for lvl in ([1, 3, 12, 19, 22] if len(data) > 50000 else [1, 3, 19]):
        add(f"{name} L{lvl}", data, zstd := z.ZstdCompressor(level=lvl))
for lvl in (1, 4, 12):
    add(f"checksum L{lvl}", base["json-ish 150k"], z.ZstdCompressor(level=lvl, write_checksum=True))
    add(f"no content size L{lvl}", base["text 120k"], z.ZstdCompressor(level=lvl, write_content_size=False))
for lvl in (-5, -1):
    add(f"negative L{lvl}", base["text 120k"], z.ZstdCompressor(level=lvl))
# streaming (multi-block, windowed frame header)
def stream(comp, data):
    o = comp.compressobj(); r = b""
    for i in range(0, len(data), 50000): r += o.compress(data[i:i + 50000])
    return r + o.flush()
add("streamed L3", base["json-ish 150k"], z.ZstdCompressor(level=3), stream=stream)
# concatenated frames + skippable frame
c = z.ZstdCompressor(level=5)
a, b = base["text 5k"], base["structured 100k"]
skip = b"\x50\x2a\x4d\x18" + struct.pack("<I", 5) + b"hello"
f = skip + c.compress(a) + c.compress(b)
cases.append({"name": "multi-frame + skippable", "b64": base64.b64encode(f).decode(), "len": len(a) + len(b), "hash": h32(a + b)})
# my own mission raw stream (generated by gen_vectors) at plugin default level 4
import os
if os.path.exists("/tmp/diplomat.raw"):
    d = open("/tmp/diplomat.raw", "rb").read()
    for lvl in (4,):
        add(f"real map stream L{lvl}", d, z.ZstdCompressor(level=lvl))
sys.stdout.write("-- GENERATED by tools/gen_zstd_vectors.py (real python-zstandard output) -- do not edit\nreturn {\n")
for c in cases:
    sys.stdout.write('\t{ name = %s, len = %d, hash = %d, b64 = [==[%s]==] },\n' % (json.dumps(c["name"]), c["len"], c["hash"], c["b64"]))
sys.stdout.write("}\n")
sys.stderr.write(f"{len(cases)} cases\n")
