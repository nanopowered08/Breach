#!/usr/bin/env python3
"""Generate src/attrmap.inc (attribute map + global attributes) for BreachValidator.luau
from the plugin's AttributesMap.lua and AttributeValidation.lua. Usage: gen_attrmap.py <plugin-src-dir>"""
import re, sys
SRC = sys.argv[1]
def rd(n): return open(f"{SRC}/SerializationTools__{n}.lua", encoding="utf-8").read()
amap = rd("AttributesMap"); val = rd("AttributeValidation")
KINDS = re.findall(r'\t([A-Z_0-9]+) = \d+,', rd("PropAttributeTypes"))
bare = []
def lit(d, where):
    d = d.strip()
    if d == "nil": return None
    if d in ("true", "false"): return d
    if re.fullmatch(r'-?\d+(\.\d+)?', d): return d
    if re.fullmatch(r'"[^"]*"', d): return d
    m = re.fullmatch(r'Vector3\.new\(([-\d. ,]+)\)', d)
    if m: x, y, z = [v.strip() for v in m.group(1).split(",")]; return "{X=%s,Y=%s,Z=%s}" % (x, y, z)
    m = re.fullmatch(r'Color3\.new\(([-\d. ,]+)\)', d)
    if m: r, g, b = [v.strip() for v in m.group(1).split(",")]; return "{R=%s,G=%s,B=%s}" % (r, g, b)
    # a bare identifier: in the plugin this evaluates to a nil global (generator typo) -> nil
    bare.append((where, d)); return None
o = []
entries = {}
for m in re.finditer(r'^\t([A-Za-z0-9_]+) = \{\n(.*?)^\t\},', amap, re.M | re.S):
    rows = []
    for a in re.finditer(r'^\t\t([A-Za-z0-9_]+) = \{AttributeType\.([A-Z_0-9]+), (.*?)\},?$', m.group(2), re.M):
        assert a.group(2) in KINDS, a.group(2)
        rows.append((a.group(1), a.group(2), lit(a.group(3), f"{m.group(1)}.{a.group(1)}")))
    entries[m.group(1)] = rows
o.append("-- >>> GENERATED by tools/gen_attrmap.py from SerializationTools (AttributesMap + AttributeValidation). DO NOT EDIT. <<<\n")
if bare:
    o.append("-- Defaults that are a BARE IDENTIFIER in the plugin source (an undefined global there, so nil at runtime):\n")
    for w, d in bare: o.append(f"--   {w} = {d}   (kept as nil here, exactly like the plugin)\n")
o.append("-- ENTRIES[component][attribute] = { kind, default }   (default is absent = nil)\nlocal ENTRIES = {\n")
for name in sorted(entries):
    o.append(f"\t{name} = {{" + ", ".join(f'{a} = {{"{k}"' + (f", {d}" if d is not None else "") + "}" for a, k, d in entries[name]) + "},\n")
o.append("}\n")
g = re.search(r'local GlobalPropAttributes = \{(.*?)\n\}\n', val, re.S).group(1)
glob = re.findall(r'\t([A-Za-z0-9_]+) = \{ PropAttributeTypes\.([A-Z_0-9]+), nil \},', g)
assert len(glob) == len(re.findall(r'PropAttributeTypes\.', g)), 'a global attribute row was not parsed'
o.append("-- GLOBALS[attribute] = kind   (accepted on every validated component; no defaults)\nlocal GLOBALS = {" + ", ".join(f'{a} = "{k}"' for a, k in glob) + "}\n")
o.append("-- <<< END GENERATED <<<\n")
sys.stdout.write("".join(o))
sys.stderr.write(f"{len(entries)} entries, {sum(len(v) for v in entries.values())} attributes, {len(glob)} globals, bare-identifier defaults: {bare}\n")
