#!/bin/sh
# Wrap text files in a Luau module so hosts without file I/O (the plain `luau` CLI) can load them:
#   sh tools/embed.sh tests/data/* > tests/_embedded.luau
echo "-- GENERATED by tools/embed.sh"
echo "return {"
for f in "$@"; do
  [ -f "$f" ] || continue
  printf '\t["%s"] = [==========[' "$(basename "$f")"
  tr -d '\r' < "$f"
  printf ']==========],\n'
done
echo "}"
