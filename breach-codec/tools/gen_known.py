#!/usr/bin/env python3
"""Regenerate tests/known_components.luau from AttributesMap.lua (see README). Usage: gen_known.py <AttributesMap.lua>"""
import re, sys
s = open(sys.argv[1], encoding="utf-8").read()
glob = "GlobalVariables OnProp ScriptMove Index CanShatter Tag TagOffset StaticTag HasTopBarrier Indestructible NoPropDamage IsSpawned Type AltProp AltPropModel FadeOutCondition CollisionGroup TagButton MultiGlass BreakAlarm BlockEMP EMPHitVariable PowerCutVariable LinkComp".split()
glob += [f"Color{i}" for i in range(6)] + [f"Material{i}" for i in range(6)]
out = "-- GENERATED by tools/gen_known.py -- component names and their attributes\nreturn {\n\tcomponents = {\n"
for m in re.finditer(r'^\t([A-Za-z0-9_]+) = \{\n(.*?)^\t\},', s, re.M | re.S):
    attrs = re.findall(r'^\t\t([A-Za-z0-9_]+) = \{AttributeType\.', m.group(2), re.M)
    out += '\t\t["%s"] = {%s},\n' % (m.group(1), ", ".join('"%s"' % a for a in attrs))
out += "\t},\n\tglobals = {" + ", ".join('"%s"' % g for g in sorted(glob)) + "},\n}\n"
sys.stdout.write(out)
