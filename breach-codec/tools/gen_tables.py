#!/usr/bin/env python3
"""Generate the data tables section of BreachCodec.luau from the plugin's type
modules (extracted as .lua files). Usage: gen_tables.py <srcdir> > tables.inc"""
import re, sys
src = sys.argv[1]
def rd(n): return open(f"{src}/SerializationTools__{n}.lua", encoding="utf-8").read()
def parse_rows(body):
    """Parse `{ "Name", "Type", default }` rows. Tolerates missing spaces before `}` and ASSERTS that
    no row was skipped (an earlier version silently dropped rows like `Vector3.new()},`)."""
    rows = re.findall(r'\{\s*"([A-Za-z0-9]+)"\s*,\s*"([A-Za-z0-9]+)"\s*,\s*(.*?)\s*\}\s*,?\s*$', body, re.M)
    expect = len(re.findall(r'^\s*\{\s*"', body, re.M))
    assert len(rows) == expect, f"row parse mismatch: parsed {len(rows)} of {expect}"
    return rows

types = rd("Types__InstanceTypes")
ids = [(k, int(v)) for k, v in re.findall(r'\t([A-Za-z]+) = (\d+),', types)]
props_src = rd("Types__InstanceProperties")
props = {}
for m in re.finditer(r'^\t([A-Za-z]+) = \{\n(.*?)^\t\},', props_src, re.M | re.S):
    props[m.group(1)] = parse_rows(m.group(2))
attr_cls = ["Model", "Folder", "Part", "BoolValue", "MeshPart", "UnionOperation"]  # WithAttributes in WriteInstance
atts = re.findall(r'\t([A-Za-z0-9]+) = (\d+),', rd("Types__AttributeTypes"))
enum_files = {
 "Material": "Types__Enums__Materials", "NormalId": "Types__Enums__NormalId", "PartType": "Types__Enums__PartTypes",
 "MeshType": "Types__Enums__MeshType", "RenderFidelity": "Types__Enums__RenderFidelity",
 "CollisionFidelity": "Types__Enums__CollisionFidelity", "TextureMode": "Types__Enums__TextureMode",
 "ParticleEmitterShape": "Types__Enums__Particles__ParticleEmitterShape",
 "ParticleEmitterShapeInOut": "Types__Enums__Particles__ParticleEmitterShapeInOut",
 "ParticleEmitterShapeStyle": "Types__Enums__Particles__ParticleEmitterShapeStyle",
 "ParticleOrientation": "Types__Enums__Particles__ParticleOrientation",
 "ResamplerMode": "Types__Enums__GUI__ResamplerMode", "SurfaceGuiSizingMode": "Types__Enums__GUI__SurfaceGuiSizingMode"}
o = ["-- >>> GENERATED by tools/gen_tables.py from SerializationTools (code version 2). DO NOT EDIT. <<<\n"]
o.append("local TYPE_BY_ID = {\n" + "".join(f'\t[{v}] = "{k}",\n' for k, v in ids) + "}\n")
o.append("local HAS_ATTRS = {" + ", ".join(f"{c} = true" for c in attr_cls) + "}\n")
o.append("local ATTR_BY_ID = {" + ", ".join(f'[{v}] = "{k}"' for k, v in atts) + "}\n")
o.append("-- per class: ordered list of {propertyName, valueType}; position = wire property id\nlocal PROPS = {\n")
for cls in [k for k, _ in ids if k not in ("Nil", "PartNoAttributes")]:
    o.append(f"\t{cls} = {{" + ", ".join(f'{{"{n}", "{t}"}}' for n, t, d in props[cls]) + "},\n")
o.append('\tPartNoAttributes = nil, -- aliased to Part below\n}\nPROPS.PartNoAttributes = PROPS.Part\n')
o.append("-- default Name per class (Name is only written when it differs)\nlocal DEFAULT_NAME = {\n")
for cls in [k for k, _ in ids if k not in ("Nil", "PartNoAttributes")]:
    nm = [d for n, t, d in props[cls] if n == "Name"]
    # Beam/Trail list Name after other props; some classes have no Name row (BlockMesh)
    o.append(f"\t{cls} = {nm[0] if nm else 'nil'},\n")
o.append("\tPartNoAttributes = \"Part\",\n}\n")
o.append("-- enum value -> name, per enum type\nlocal ENUMS = {\n")
for en, f in enum_files.items():
    pairs = re.findall(r'([A-Za-z0-9]+) = (\d+)', rd(f))
    o.append(f"\t{en} = {{" + ", ".join(f'[{v}] = "{k}"' for k, v in pairs) + "},\n")
o.append("}\n-- <<< END GENERATED <<<\n")
print("".join(o), end="")
