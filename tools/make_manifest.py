#!/usr/bin/env python3
"""Write manifest.txt: one line per loadable file, "<sha256>  <repo path>".

The Roblox loader fetches this file every 5 minutes; a changed hash means "hot-swap that file".
Run it from anywhere inside the repo, before you push:

    python3 tools/make_manifest.py            # rewrite manifest.txt
    python3 tools/make_manifest.py --check    # exit 1 if manifest.txt is stale (for CI)
    python3 tools/make_manifest.py --install-hook   # regenerate + `git add` automatically on every commit

Which files are listed: breach-codec/Breach*.luau (the built, standalone modules) and everything under wrapper/ that is
.luau or .lua, except tests/ and *.server.luau / *.client.luau entry scripts (those are placed in Studio by hand).
"""
import hashlib, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "# breach-manifest v1  (generated by tools/make_manifest.py; do not edit)\n"


def listed_files():
    out = []
    codec = os.path.join(ROOT, "breach-codec")
    if os.path.isdir(codec):
        for name in sorted(os.listdir(codec)):
            if name.startswith("Breach") and name.endswith(".luau"):
                out.append("breach-codec/" + name)
    wrapper = os.path.join(ROOT, "wrapper")
    for dirpath, dirs, names in os.walk(wrapper):
        dirs[:] = [d for d in dirs if d != "tests"]  # tests are not loaded by the game
        for name in sorted(names):
            if name.endswith((".luau", ".lua")) and not name.endswith((".server.luau", ".client.luau")):
                rel = os.path.relpath(os.path.join(dirpath, name), ROOT).replace(os.sep, "/")
                out.append(rel)
    return sorted(set(out))


def build():
    lines = [HEADER]
    for rel in listed_files():
        with open(os.path.join(ROOT, rel), "rb") as f:
            data = f.read()
        if b"\r\n" in data:
            sys.exit(f"{rel} has CRLF line endings; the loader hashes the exact bytes GitHub serves. "
                     "Convert it to LF (or set `* text=auto eol=lf` in .gitattributes).")
        lines.append(f"{hashlib.sha256(data).hexdigest()}  {rel}\n")
    return "".join(lines)


def main():
    text = build()
    path = os.path.join(ROOT, "manifest.txt")
    if "--install-hook" in sys.argv:
        hook = os.path.join(ROOT, ".git", "hooks", "pre-commit")
        with open(hook, "w") as f:
            f.write("#!/bin/sh\npython3 tools/make_manifest.py && git add manifest.txt\n")
        os.chmod(hook, 0o755)
        print("installed", hook)
        return
    if "--check" in sys.argv:
        current = open(path).read() if os.path.exists(path) else ""
        if current != text:
            print("manifest.txt is stale; run tools/make_manifest.py")
            sys.exit(1)
        print("manifest.txt is up to date")
        return
    with open(path, "w", newline="\n") as f:
        f.write(text)
    print(f"wrote manifest.txt ({text.count(chr(10)) - 1} files)")


if __name__ == "__main__":
    main()
